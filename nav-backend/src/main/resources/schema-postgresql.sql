-- Standalone PostgreSQL 17 bootstrap reference for manual backend deployments.
-- This file is the canonical schema used by the external PostgreSQL installer.
BEGIN;

SET TIME ZONE 'Asia/Hong_Kong';

CREATE TABLE IF NOT EXISTS schema_migration (
    filename VARCHAR(255) PRIMARY KEY,
    checksum CHAR(64) NOT NULL,
    applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_schema_migration_checksum CHECK (checksum ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    nickname VARCHAR(50),
    avatar VARCHAR(255),
    role VARCHAR(30) NOT NULL DEFAULT 'admin',
    status BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sys_user_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS site_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_name VARCHAR(50) NOT NULL,
    site_description VARCHAR(255),
    publish_url VARCHAR(255),
    background_type VARCHAR(20) NOT NULL DEFAULT 'color',
    background_color VARCHAR(30) NOT NULL DEFAULT '#050505',
    background_image VARCHAR(500),
    mobile_background_image VARCHAR(500),
    font_color VARCHAR(30) NOT NULL DEFAULT '#ffffff',
    background_effect BOOLEAN NOT NULL DEFAULT FALSE,
    music_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    music_url VARCHAR(500),
    subscribe_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    top_content_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    message_text VARCHAR(100),
    version INTEGER NOT NULL DEFAULT 0,
    install_completed_at TIMESTAMP,
    install_instance_id UUID NOT NULL DEFAULT gen_random_uuid(),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_site_config_background_type CHECK (background_type IN ('color', 'image')),
    CONSTRAINT chk_site_config_version_range CHECK (version >= 0)
);

CREATE TABLE IF NOT EXISTS portable_import_guard (
    id INTEGER PRIMARY KEY,
    CONSTRAINT chk_portable_import_guard_singleton CHECK (id = 1)
);
INSERT INTO portable_import_guard (id) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS portable_import_operation (
    job_id VARCHAR(64) PRIMARY KEY,
    preview_token VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    started_at TIMESTAMP NOT NULL,
    committed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    site_version INTEGER NOT NULL,
    CONSTRAINT uk_portable_import_preview UNIQUE (preview_token)
);
CREATE INDEX IF NOT EXISTS idx_portable_import_user_committed
    ON portable_import_operation (user_id, committed_at DESC);

CREATE TABLE IF NOT EXISTS nav_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    icon VARCHAR(100),
    sort_order INTEGER NOT NULL DEFAULT 0,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_nav_category_sort ON nav_category (sort_order, id);

CREATE TABLE IF NOT EXISTS nav_bookmark (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    url VARCHAR(500) NOT NULL,
    icon VARCHAR(255),
    description VARCHAR(255),
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_recommend BOOLEAN NOT NULL DEFAULT FALSE,
    is_external BOOLEAN NOT NULL DEFAULT TRUE,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_nav_bookmark_category
        FOREIGN KEY (category_id) REFERENCES nav_category (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_nav_bookmark_category_sort
    ON nav_bookmark (category_id, sort_order, id);

CREATE TABLE IF NOT EXISTS search_engine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    icon VARCHAR(255),
    search_url VARCHAR(500) NOT NULL,
    placeholder VARCHAR(100),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_search_engine_one_visible_default
    ON search_engine ((1)) WHERE is_default IS TRUE AND visible IS TRUE;
CREATE INDEX IF NOT EXISTS idx_search_engine_visible_sort
    ON search_engine (visible, sort_order, id);

CREATE TABLE IF NOT EXISTS custom_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(50) NOT NULL,
    url VARCHAR(500) NOT NULL,
    position VARCHAR(20) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_custom_link_position CHECK (position IN ('header', 'footer'))
);
CREATE INDEX IF NOT EXISTS idx_custom_link_position_sort
    ON custom_link (position, sort_order, id);

CREATE OR REPLACE FUNCTION nav_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at = CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sys_user_updated_at ON sys_user;
CREATE TRIGGER trg_sys_user_updated_at BEFORE UPDATE ON sys_user
    FOR EACH ROW EXECUTE FUNCTION nav_set_updated_at();
DROP TRIGGER IF EXISTS trg_site_config_updated_at ON site_config;
CREATE TRIGGER trg_site_config_updated_at BEFORE UPDATE ON site_config
    FOR EACH ROW EXECUTE FUNCTION nav_set_updated_at();
DROP TRIGGER IF EXISTS trg_nav_category_updated_at ON nav_category;
CREATE TRIGGER trg_nav_category_updated_at BEFORE UPDATE ON nav_category
    FOR EACH ROW EXECUTE FUNCTION nav_set_updated_at();
DROP TRIGGER IF EXISTS trg_nav_bookmark_updated_at ON nav_bookmark;
CREATE TRIGGER trg_nav_bookmark_updated_at BEFORE UPDATE ON nav_bookmark
    FOR EACH ROW EXECUTE FUNCTION nav_set_updated_at();
DROP TRIGGER IF EXISTS trg_search_engine_updated_at ON search_engine;
CREATE TRIGGER trg_search_engine_updated_at BEFORE UPDATE ON search_engine
    FOR EACH ROW EXECUTE FUNCTION nav_set_updated_at();
DROP TRIGGER IF EXISTS trg_custom_link_updated_at ON custom_link;
CREATE TRIGGER trg_custom_link_updated_at BEFORE UPDATE ON custom_link
    FOR EACH ROW EXECUTE FUNCTION nav_set_updated_at();

